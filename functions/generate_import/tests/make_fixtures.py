"""
Generates the synthetic fixture folder used by test_tabular_parser.py.

These stand in for the real-world files task-parser-hardening.txt names
(1-B.xls, Teacher_Information.xlsx) — the actual files live on Sid's machine,
not in this repo. test_tabular_parser.py iterates over whatever's in
fixtures/ dynamically, so dropping the real files in alongside these (or
replacing these) picks them up automatically, no test code changes needed.

Run once with: .venv_test/Scripts/python.exe tests/make_fixtures.py
"""
import io
import os

from openpyxl import Workbook

FIXTURES_DIR = os.path.join(os.path.dirname(__file__), "fixtures")


def _save(name, raw_bytes):
    path = os.path.join(FIXTURES_DIR, name)
    with open(path, "wb") as f:
        f.write(raw_bytes)
    print(f"wrote {name} ({len(raw_bytes)} bytes)")


def _xlsx_bytes(build_fn):
    wb = Workbook()
    build_fn(wb)
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


