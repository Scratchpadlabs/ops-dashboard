def _cp1252_csv():
    # café/résumé-style accented characters that break under strict utf-8.
    text = (
        "Sr No,Name,Class,Section,Gender,DOB,Father Name,Contact\r\n"
        "1,Zoe Dsouza,6,A,F,19/07/2013,Andr\xe9 Dsouza,9555555555\r\n"
        "2,Rene\xe9 Fernandes,6,A,F,04/05/2013,Jos\xe9 Fernandes,9666666666\r\n"
    )
    return text.encode("cp1252")


