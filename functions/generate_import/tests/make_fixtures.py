# 4. Excel-serial DOBs — plain numbers (no date number_format), the way a
#    badly-exported sheet or a copy-paste-values often leaves them.
def _excel_serial(y, m, d):
    from datetime import date
    return (date(y, m, d) - date(1899, 12, 30)).days


